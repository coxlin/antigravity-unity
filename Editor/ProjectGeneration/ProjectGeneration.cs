using System.Security;
using System.Security.Cryptography;
using System.Text;
using Assembly = UnityEditor.Compilation.Assembly;
using PackageInfo = UnityEditor.PackageManager.PackageInfo;

namespace Coxlin.Antigravity.Editor.ProjectGeneration
{
    /// <summary>
    /// Generates SDK-style .csproj files and a matching .sln from Unity's compilation
    /// pipeline. Files are only rewritten when their content hash changes so that the
    /// IDE does not reload projects unnecessarily.
    /// </summary>
    public class ProjectGeneration : IGenerator
    {
        private const string GenerationFlagsKey = "Antigravity_ProjectGenerationFlag";
        private const string GeneratedFileMarker = "Generated by Coxlin Antigravity ProjectGeneration";
        private const string CSharpProjectTypeGuid = "{FAE04EC0-301F-11D3-BF4B-00C04F79EFBC}";
        private const string TargetFramework = "netstandard2.1";
        private const string DefaultLangVersion = "9.0";
        private const string GeneratedOutputRoot = "Temp/Bin/Debug";

        private static readonly UTF8Encoding _utf8NoBom = new UTF8Encoding(false);

        private static readonly HashSet<string> _relevantExtensions = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
        {
            ".cs",
            ".asmdef",
            ".asmref",
            ".rsp",
            ".shader",
            ".compute",
            ".hlsl",
            ".cginc",
            ".uss",
            ".uxml",
            ".dll"
        };

        private static readonly HashSet<string> _projectContentExtensions = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
        {
            ".asmdef",
            ".asmref",
            ".shader",
            ".compute",
            ".hlsl",
            ".cginc",
            ".uss",
            ".uxml"
        };

        private static readonly HashSet<string> _prunedDirectoryNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
        {
            "obj",
            "bin",
            ".git",
            ".svn",
            ".vs",
            ".idea",
            ".gradle",
            "node_modules",
            "Library",
            "Temp",
            "Logs"
        };

        public ProjectGeneration()
            : this(Directory.GetParent(Application.dataPath)?.FullName ?? string.Empty)
        {
        }

        public ProjectGeneration(string projectDirectory)
        {
            ProjectDirectory = NormalizeDirectory(projectDirectory);
        }

        public string ProjectDirectory { get; }

        public ProjectGenerationFlag GenerationFlags
        {
            get
            {
                return (ProjectGenerationFlag)EditorPrefs.GetInt(
                    GenerationFlagsKey,
                    (int)(ProjectGenerationFlag.Embedded | ProjectGenerationFlag.Local));
            }
            set
            {
                EditorPrefs.SetInt(GenerationFlagsKey, (int)value);
            }
        }

        public string SolutionFile()
        {
            string directoryName = Path.GetFileName(
                ProjectDirectory.TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar));
            return Path.Combine(ProjectDirectory, directoryName + ".sln");
        }

        public bool HasSolutionBeenGenerated()
        {
            return File.Exists(SolutionFile());
        }

        public bool SyncIfNeeded(string[] addedFiles, string[] deletedFiles, string[] movedFiles, string[] movedFromFiles, string[] importedFiles)
        {
            if (!HasSolutionBeenGenerated())
            {
                Sync();
                return true;
            }

            if (ContainsRelevantChange(addedFiles) ||
                ContainsRelevantChange(deletedFiles) ||
                ContainsRelevantChange(movedFiles) ||
                ContainsRelevantChange(movedFromFiles) ||
                ContainsRelevantChange(importedFiles))
            {
                Sync();
                return true;
            }

            return false;
        }

        public void Sync()
        {
            if (string.IsNullOrEmpty(ProjectDirectory) || !Directory.Exists(ProjectDirectory))
            {
                return;
            }

            Assembly[] editorAssemblies = CompilationPipeline.GetAssemblies(AssembliesType.Editor) ?? new Assembly[0];
            var projects = new List<ProjectInfo>();
            var editorAssemblyNames = new HashSet<string>(StringComparer.Ordinal);
            foreach (Assembly assembly in editorAssemblies)
            {
                if (assembly != null && !string.IsNullOrEmpty(assembly.name))
                {
                    editorAssemblyNames.Add(assembly.name);
                }
            }

            var usedProjectNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            AddProjects(editorAssemblies, false, editorAssemblyNames, usedProjectNames, projects);

            if ((GenerationFlags & ProjectGenerationFlag.PlayerAssemblies) != 0)
            {
                Assembly[] playerAssemblies = CompilationPipeline.GetAssemblies(AssembliesType.Player) ?? new Assembly[0];
                AddProjects(playerAssemblies, true, editorAssemblyNames, usedProjectNames, projects);
            }

            CollectNoneFiles(projects);

            var editorProjects = new Dictionary<Assembly, ProjectInfo>();
            var playerProjects = new Dictionary<Assembly, ProjectInfo>();
            foreach (ProjectInfo project in projects)
            {
                if (project.IsPlayer)
                {
                    playerProjects[project.Assembly] = project;
                }
                else
                {
                    editorProjects[project.Assembly] = project;
                }
            }

            var generatedFiles = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (ProjectInfo project in projects)
            {
                string projectPath = Path.Combine(ProjectDirectory, project.Name + ".csproj");
                string content = GenerateProjectXml(project, projects, editorProjects, playerProjects);
                WriteFileIfChanged(projectPath, content);
                generatedFiles.Add(Path.GetFullPath(projectPath));
            }

            string solutionPath = SolutionFile();
            WriteFileIfChanged(solutionPath, GenerateSolution(projects));
            generatedFiles.Add(Path.GetFullPath(solutionPath));

            DeleteStaleProjectFiles(generatedFiles);
        }

        private void AddProjects(Assembly[] assemblies, bool isPlayer, HashSet<string> editorAssemblyNames, HashSet<string> usedProjectNames, List<ProjectInfo> projects)
        {
            foreach (Assembly assembly in assemblies.OrderBy(a => a == null ? string.Empty : a.name, StringComparer.Ordinal))
            {
                if (assembly == null || string.IsNullOrEmpty(assembly.name))
                {
                    continue;
                }

                string[] sourceFiles = assembly.sourceFiles;
                if (sourceFiles == null || sourceFiles.Length == 0)
                {
                    continue;
                }

                string firstSource = sourceFiles.FirstOrDefault(s => !string.IsNullOrEmpty(s));
                PackageInfo packageInfo = FindPackageInfo(firstSource);
                if (!ShouldIncludeAssembly(packageInfo))
                {
                    continue;
                }

                var project = new ProjectInfo
                {
                    Assembly = assembly,
                    IsPlayer = isPlayer,
                    PackageInfo = packageInfo
                };

                foreach (string sourceFile in sourceFiles)
                {
                    if (string.IsNullOrEmpty(sourceFile))
                    {
                        continue;
                    }

                    string resolved = ResolveSourceFile(sourceFile, packageInfo);
                    if (string.IsNullOrEmpty(resolved))
                    {
                        continue;
                    }

                    if (project.SourceFileSet.Add(resolved))
                    {
                        project.SourceFiles.Add(resolved);
                    }
                }

                if (project.SourceFiles.Count == 0)
                {
                    continue;
                }

                string baseName = assembly.name;
                if (isPlayer && editorAssemblyNames.Contains(baseName))
                {
                    // Editor and player variants share an assembly name; give the player
                    // variant its own project file so both can coexist in the solution.
                    baseName += ".Player";
                }

                project.Name = MakeUniqueProjectName(baseName, usedProjectNames);
                project.RootDirectory = ResolveRootDirectory(project);
                projects.Add(project);
            }
        }

        private bool ShouldIncludeAssembly(PackageInfo packageInfo)
        {
            if (packageInfo == null)
            {
                // Assemblies under Assets/ are always part of the project.
                return true;
            }

            ProjectGenerationFlag flags = GenerationFlags;
            switch (packageInfo.source)
            {
                case PackageSource.Embedded:
                    return (flags & ProjectGenerationFlag.Embedded) != 0;
                case PackageSource.Local:
                    return (flags & ProjectGenerationFlag.Local) != 0;
                case PackageSource.Registry:
                    return (flags & ProjectGenerationFlag.Registry) != 0;
                case PackageSource.Git:
                    return (flags & ProjectGenerationFlag.Git) != 0;
                case PackageSource.BuiltIn:
                    return (flags & ProjectGenerationFlag.BuiltIn) != 0;
                case PackageSource.LocalTarball:
                    return (flags & ProjectGenerationFlag.LocalTarBall) != 0;
                case PackageSource.Unknown:
                default:
                    return (flags & ProjectGenerationFlag.Unknown) != 0;
            }
        }

        private void CollectNoneFiles(List<ProjectInfo> projects)
        {
            var assemblyRoots = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (ProjectInfo project in projects)
            {
                if (!string.IsNullOrEmpty(project.RootDirectory))
                {
                    assemblyRoots.Add(project.RootDirectory);
                }
            }

            var scannedRoots = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            var claimedFiles = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            // Deeper roots are scanned first so that files belonging to nested assemblies
            // are attributed to the most specific project, then parent scans prune them.
            foreach (ProjectInfo project in projects
                .Where(p => !string.IsNullOrEmpty(p.RootDirectory))
                .OrderByDescending(p => p.RootDirectory.Length)
                .ThenBy(p => p.Name, StringComparer.OrdinalIgnoreCase))
            {
                if (!scannedRoots.Add(project.RootDirectory))
                {
                    continue;
                }

                ScanDirectoryForProjectContent(
                    project.RootDirectory,
                    project.RootDirectory,
                    assemblyRoots,
                    claimedFiles,
                    project.NoneFiles);

                project.NoneFiles.Sort(StringComparer.OrdinalIgnoreCase);
            }
        }

        private static void ScanDirectoryForProjectContent(string root, string directory, HashSet<string> assemblyRoots, HashSet<string> claimedFiles, List<string> results)
        {
            if (!PathsEqual(directory, root) && assemblyRoots.Contains(directory))
            {
                // Another generated assembly owns this subtree.
                return;
            }

            if (!PathsEqual(directory, root) && _prunedDirectoryNames.Contains(Path.GetFileName(directory)))
            {
                return;
            }

            string[] files;
            try
            {
                files = Directory.GetFiles(directory);
            }
            catch (IOException)
            {
                return;
            }
            catch (UnauthorizedAccessException)
            {
                return;
            }

            foreach (string file in files)
            {
                if (!_projectContentExtensions.Contains(Path.GetExtension(file)))
                {
                    continue;
                }

                string fullPath;
                try
                {
                    fullPath = Path.GetFullPath(file);
                }
                catch (ArgumentException)
                {
                    continue;
                }
                catch (NotSupportedException)
                {
                    continue;
                }
                catch (PathTooLongException)
                {
                    continue;
                }

                if (claimedFiles.Add(fullPath))
                {
                    results.Add(fullPath);
                }
            }

            string[] subdirectories;
            try
            {
                subdirectories = Directory.GetDirectories(directory);
            }
            catch (IOException)
            {
                return;
            }
            catch (UnauthorizedAccessException)
            {
                return;
            }

            foreach (string subdirectory in subdirectories)
            {
                if (HasReparsePoint(subdirectory))
                {
                    continue;
                }

                ScanDirectoryForProjectContent(root, subdirectory, assemblyRoots, claimedFiles, results);
            }
        }

        private string ResolveRootDirectory(ProjectInfo project)
        {
            string commonDirectory = FindCommonDirectory(project.SourceFiles);
            if (string.IsNullOrEmpty(commonDirectory))
            {
                return null;
            }

            string boundary = ProjectDirectory;
            if (!IsSameOrAncestor(ProjectDirectory, commonDirectory))
            {
                string packageRoot = NormalizeDirectory(project.PackageInfo?.resolvedPath);
                boundary = !string.IsNullOrEmpty(packageRoot) && IsSameOrAncestor(packageRoot, commonDirectory)
                    ? packageRoot
                    : commonDirectory;
            }

            return FindAssemblyDefinitionDirectory(commonDirectory, boundary);
        }

        private string GenerateProjectXml(ProjectInfo project, List<ProjectInfo> allProjects, Dictionary<Assembly, ProjectInfo> editorProjects, Dictionary<Assembly, ProjectInfo> playerProjects)
        {
            Assembly assembly = project.Assembly;
            var projectReferences = new SortedDictionary<string, ProjectInfo>(StringComparer.OrdinalIgnoreCase);
            var assemblyReferences = new SortedDictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            Dictionary<Assembly, ProjectInfo> flavorProjects = project.IsPlayer ? playerProjects : editorProjects;

            Assembly[] references = assembly.assemblyReferences;
            if (references != null)
            {
                foreach (Assembly reference in references)
                {
                    if (reference == null || string.Equals(reference.name, assembly.name, StringComparison.Ordinal))
                    {
                        continue;
                    }

                    ProjectInfo target;
                    if (!flavorProjects.TryGetValue(reference, out target) || target == project)
                    {
                        // Reference instances can differ between pipeline queries; fall
                        // back to a name match within the same (Editor or Player) flavor.
                        target = allProjects.FirstOrDefault(
                            p => p.IsPlayer == project.IsPlayer &&
                                 p != project &&
                                 string.Equals(p.Assembly.name, reference.name, StringComparison.Ordinal));
                    }

                    if (target != null)
                    {
                        projectReferences[target.Name] = target;
                        continue;
                    }

                    string referenceName = string.IsNullOrEmpty(reference.name)
                        ? Path.GetFileNameWithoutExtension(reference.outputPath)
                        : reference.name;

                    if (string.IsNullOrEmpty(referenceName) || assemblyReferences.ContainsKey(referenceName))
                    {
                        continue;
                    }

                    assemblyReferences[referenceName] = reference.outputPath;
                }
            }

            string[] compiledReferences = assembly.compiledAssemblyReferences;
            if (compiledReferences != null)
            {
                foreach (string referencePath in compiledReferences)
                {
                    if (string.IsNullOrEmpty(referencePath))
                    {
                        continue;
                    }

                    string referenceName = Path.GetFileNameWithoutExtension(referencePath);
                    if (string.IsNullOrEmpty(referenceName) ||
                        string.Equals(referenceName, assembly.name, StringComparison.OrdinalIgnoreCase))
                    {
                        continue;
                    }

                    if (projectReferences.ContainsKey(referenceName) || assemblyReferences.ContainsKey(referenceName))
                    {
                        continue;
                    }

                    assemblyReferences[referenceName] = referencePath;
                }
            }

            var builder = new StringBuilder(4096);
            builder.Append("<Project Sdk=\"Microsoft.NET.Sdk\">\n");
            builder.Append("  <!-- ").Append(GeneratedFileMarker).Append(" -->\n");
            builder.Append("  <PropertyGroup>\n");
            AppendElement(builder, "    ", "TargetFramework", TargetFramework);
            AppendElement(builder, "    ", "LangVersion", GetLanguageVersion(assembly));
            AppendElement(builder, "    ", "AssemblyName", assembly.name);
            AppendElement(builder, "    ", "RootNamespace", GetRootNamespace(assembly.name));
            AppendElement(builder, "    ", "OutputType", "Library");
            AppendElement(builder, "    ", "GenerateAssemblyInfo", "false");
            AppendElement(builder, "    ", "EnableDefaultItems", "false");
            AppendElement(builder, "    ", "AppendTargetFrameworkToOutputPath", "false");
            AppendElement(builder, "    ", "OutputPath", GeneratedOutputRoot + "/" + project.Name + "/");
            AppendElement(builder, "    ", "AllowUnsafeBlocks", IsUnsafeCodeAllowed(assembly) ? "true" : "false");

            string defines = GetDefineConstants(assembly);
            if (!string.IsNullOrEmpty(defines))
            {
                AppendElement(builder, "    ", "DefineConstants", defines);
            }

            builder.Append("  </PropertyGroup>\n");

            builder.Append("  <ItemGroup>\n");
            foreach (string sourceFile in project.SourceFiles.OrderBy(f => f, StringComparer.OrdinalIgnoreCase))
            {
                builder.Append("    <Compile Include=\"").Append(Escape(ToProjectPath(sourceFile))).Append("\" />\n");
            }
            builder.Append("  </ItemGroup>\n");

            if (project.NoneFiles.Count > 0)
            {
                builder.Append("  <ItemGroup>\n");
                foreach (string contentFile in project.NoneFiles)
                {
                    builder.Append("    <None Include=\"").Append(Escape(ToProjectPath(contentFile))).Append("\" />\n");
                }
                builder.Append("  </ItemGroup>\n");
            }

            if (projectReferences.Count > 0)
            {
                builder.Append("  <ItemGroup>\n");
                foreach (ProjectInfo reference in projectReferences.Values)
                {
                    builder.Append("    <ProjectReference Include=\"")
                        .Append(Escape(reference.Name + ".csproj"))
                        .Append("\">\n");
                    builder.Append("      <Project>").Append(GenerateProjectGuid(reference.Name)).Append("</Project>\n");
                    builder.Append("      <Name>").Append(Escape(reference.Name)).Append("</Name>\n");
                    builder.Append("    </ProjectReference>\n");
                }
                builder.Append("  </ItemGroup>\n");
            }

            if (assemblyReferences.Count > 0)
            {
                builder.Append("  <ItemGroup>\n");
                foreach (KeyValuePair<string, string> reference in assemblyReferences)
                {
                    if (string.IsNullOrEmpty(reference.Value))
                    {
                        builder.Append("    <Reference Include=\"").Append(Escape(reference.Key)).Append("\" />\n");
                        continue;
                    }

                    builder.Append("    <Reference Include=\"").Append(Escape(reference.Key)).Append("\">\n");
                    builder.Append("      <HintPath>")
                        .Append(Escape(ToProjectPath(reference.Value)))
                        .Append("</HintPath>\n");
                    builder.Append("    </Reference>\n");
                }
                builder.Append("  </ItemGroup>\n");
            }

            builder.Append("</Project>\n");
            return builder.ToString();
        }

        private static string GenerateSolution(List<ProjectInfo> projects)
        {
            var orderedProjects = projects
                .OrderBy(p => p.Name, StringComparer.OrdinalIgnoreCase)
                .ToList();

            var builder = new StringBuilder(1024);
            builder.Append("Microsoft Visual Studio Solution File, Format Version 12.00\n");
            builder.Append("# Visual Studio 15\n");
            builder.Append("VisualStudioVersion = 15.0.26124.0\n");
            builder.Append("MinimumVisualStudioVersion = 15.0.26124.0\n");

            foreach (ProjectInfo project in orderedProjects)
            {
                builder.Append("Project(\"")
                    .Append(CSharpProjectTypeGuid)
                    .Append("\") = \"")
                    .Append(project.Name)
                    .Append("\", \"")
                    .Append(project.Name)
                    .Append(".csproj\", \"")
                    .Append(GenerateProjectGuid(project.Name))
                    .Append("\"\n");
                builder.Append("EndProject\n");
            }

            builder.Append("Global\n");
            builder.Append("\tGlobalSection(SolutionConfigurationPlatforms) = preSolution\n");
            builder.Append("\t\tDebug|Any CPU = Debug|Any CPU\n");
            builder.Append("\t\tRelease|Any CPU = Release|Any CPU\n");
            builder.Append("\tEndGlobalSection\n");
            builder.Append("\tGlobalSection(ProjectConfigurationPlatforms) = postSolution\n");

            foreach (ProjectInfo project in orderedProjects)
            {
                string guid = GenerateProjectGuid(project.Name);
                builder.Append("\t\t").Append(guid).Append(".Debug|Any CPU.ActiveCfg = Debug|Any CPU\n");
                builder.Append("\t\t").Append(guid).Append(".Debug|Any CPU.Build.0 = Debug|Any CPU\n");
                builder.Append("\t\t").Append(guid).Append(".Release|Any CPU.ActiveCfg = Release|Any CPU\n");
                builder.Append("\t\t").Append(guid).Append(".Release|Any CPU.Build.0 = Release|Any CPU\n");
            }

            builder.Append("\tEndGlobalSection\n");
            builder.Append("\tGlobalSection(SolutionProperties) = preSolution\n");
            builder.Append("\t\tHideSolutionNode = FALSE\n");
            builder.Append("\tEndGlobalSection\n");
            builder.Append("EndGlobal\n");
            return builder.ToString();
        }

        private static string GenerateProjectGuid(string projectName)
        {
            // MD5 is used only to derive a stable project GUID from the project name,
            // matching the deterministic GUIDs Visual Studio expects. It is not security-sensitive.
            using (MD5 md5 = MD5.Create())
            {
                byte[] hash = md5.ComputeHash(Encoding.UTF8.GetBytes(projectName ?? string.Empty));
                var builder = new StringBuilder(38);
                builder.Append('{');
                for (int i = 0; i < 16; i++)
                {
                    if (i == 4 || i == 6 || i == 8 || i == 10)
                    {
                        builder.Append('-');
                    }

                    builder.Append(hash[i].ToString("X2"));
                }

                builder.Append('}');
                return builder.ToString();
            }
        }

        private static void WriteFileIfChanged(string path, string content)
        {
            byte[] bytes = _utf8NoBom.GetBytes(content);

            if (File.Exists(path))
            {
                byte[] existing = null;
                try
                {
                    existing = File.ReadAllBytes(path);
                }
                catch (IOException)
                {
                }
                catch (UnauthorizedAccessException)
                {
                }

                if (existing != null && HashesMatch(existing, bytes))
                {
                    return;
                }
            }

            string directory = Path.GetDirectoryName(path);
            if (!string.IsNullOrEmpty(directory) && !Directory.Exists(directory))
            {
                Directory.CreateDirectory(directory);
            }

            File.WriteAllBytes(path, bytes);
        }

        private static bool HashesMatch(byte[] left, byte[] right)
        {
            using (SHA256 sha256 = SHA256.Create())
            {
                byte[] leftHash = sha256.ComputeHash(left);
                byte[] rightHash = sha256.ComputeHash(right);
                if (leftHash.Length != rightHash.Length)
                {
                    return false;
                }

                for (int i = 0; i < leftHash.Length; i++)
                {
                    if (leftHash[i] != rightHash[i])
                    {
                        return false;
                    }
                }

                return true;
            }
        }

        private void DeleteStaleProjectFiles(HashSet<string> generatedFiles)
        {
            string[] projectFiles;
            try
            {
                projectFiles = Directory.GetFiles(ProjectDirectory, "*.csproj", SearchOption.TopDirectoryOnly);
            }
            catch (IOException)
            {
                return;
            }
            catch (UnauthorizedAccessException)
            {
                return;
            }

            foreach (string projectFile in projectFiles)
            {
                string fullPath;
                try
                {
                    fullPath = Path.GetFullPath(projectFile);
                }
                catch (ArgumentException)
                {
                    continue;
                }
                catch (NotSupportedException)
                {
                    continue;
                }

                if (generatedFiles.Contains(fullPath) || !LooksLikeGeneratedProjectFile(fullPath))
                {
                    continue;
                }

                try
                {
                    File.Delete(fullPath);
                }
                catch (IOException)
                {
                }
                catch (UnauthorizedAccessException)
                {
                }
            }
        }

        private static bool LooksLikeGeneratedProjectFile(string path)
        {
            string content;
            try
            {
                content = File.ReadAllText(path);
            }
            catch (IOException)
            {
                return false;
            }
            catch (UnauthorizedAccessException)
            {
                return false;
            }

            return content.IndexOf(GeneratedFileMarker, StringComparison.Ordinal) >= 0;
        }

        private static string GetLanguageVersion(Assembly assembly)
        {
            ScriptCompilerOptions options = assembly.compilerOptions;
            if (options != null && !string.IsNullOrEmpty(options.LanguageVersion))
            {
                return options.LanguageVersion.Trim();
            }

            return DefaultLangVersion;
        }

        private static bool IsUnsafeCodeAllowed(Assembly assembly)
        {
            ScriptCompilerOptions options = assembly.compilerOptions;
            return options != null && options.AllowUnsafeCode;
        }

        private static string GetDefineConstants(Assembly assembly)
        {
            string[] defines = assembly.defines;
            if (defines == null || defines.Length == 0)
            {
                return string.Empty;
            }

            var seen = new HashSet<string>(StringComparer.Ordinal);
            var uniqueDefines = new List<string>(defines.Length);
            foreach (string define in defines)
            {
                if (string.IsNullOrEmpty(define))
                {
                    continue;
                }

                string trimmed = define.Trim();
                if (trimmed.Length == 0)
                {
                    continue;
                }

                if (seen.Add(trimmed))
                {
                    uniqueDefines.Add(trimmed);
                }
            }

            return string.Join(";", uniqueDefines);
        }

        private static string GetRootNamespace(string assemblyName)
        {
            if (string.IsNullOrEmpty(assemblyName))
            {
                return "Assembly";
            }

            var builder = new StringBuilder(assemblyName.Length);
            foreach (char character in assemblyName)
            {
                builder.Append(char.IsLetterOrDigit(character) || character == '_' || character == '.'
                    ? character
                    : '_');
            }

            string rootNamespace = builder.ToString().Trim('.');
            if (rootNamespace.Length == 0)
            {
                return "Assembly";
            }

            return char.IsDigit(rootNamespace[0]) ? "_" + rootNamespace : rootNamespace;
        }

        private static void AppendElement(StringBuilder builder, string indentation, string name, string value)
        {
            builder.Append(indentation)
                .Append('<')
                .Append(name)
                .Append('>')
                .Append(Escape(value))
                .Append("</")
                .Append(name)
                .Append(">\n");
        }

        private static string Escape(string value)
        {
            if (string.IsNullOrEmpty(value))
            {
                return string.Empty;
            }

            return SecurityElement.Escape(value) ?? string.Empty;
        }

        private string ToProjectPath(string path)
        {
            if (string.IsNullOrEmpty(path))
            {
                return string.Empty;
            }

            string fullPath;
            try
            {
                fullPath = Path.GetFullPath(Path.IsPathRooted(path) ? path : Path.Combine(ProjectDirectory, path));
            }
            catch (ArgumentException)
            {
                return ToForwardSlashes(path);
            }
            catch (NotSupportedException)
            {
                return ToForwardSlashes(path);
            }
            catch (PathTooLongException)
            {
                return ToForwardSlashes(path);
            }

            if (!string.IsNullOrEmpty(ProjectDirectory) && IsSameOrAncestor(ProjectDirectory, fullPath))
            {
                string relative = fullPath
                    .Substring(ProjectDirectory.Length)
                    .TrimStart(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
                return ToForwardSlashes(relative);
            }

            return ToForwardSlashes(fullPath);
        }

        private static string ToForwardSlashes(string path)
        {
            return path.Replace('\\', '/');
        }

        private string ResolveSourceFile(string sourceFile, PackageInfo packageInfo)
        {
            string physicalPath = ResolvePhysicalPath(sourceFile);
            if (!string.IsNullOrEmpty(physicalPath) && File.Exists(physicalPath))
            {
                return physicalPath;
            }

            string packagePath = ResolvePackagePath(sourceFile, packageInfo);
            if (!string.IsNullOrEmpty(packagePath) && File.Exists(packagePath))
            {
                return packagePath;
            }

            PackageInfo discoveredPackage = FindPackageInfo(sourceFile);
            if (discoveredPackage != null && discoveredPackage != packageInfo)
            {
                packagePath = ResolvePackagePath(sourceFile, discoveredPackage);
                if (!string.IsNullOrEmpty(packagePath) && File.Exists(packagePath))
                {
                    return packagePath;
                }
            }

            return null;
        }

        private string ResolvePhysicalPath(string path)
        {
            try
            {
                string combined = Path.IsPathRooted(path) ? path : Path.Combine(ProjectDirectory, path);
                return Path.GetFullPath(combined);
            }
            catch (ArgumentException)
            {
                return null;
            }
            catch (NotSupportedException)
            {
                return null;
            }
            catch (PathTooLongException)
            {
                return null;
            }
        }

        private static string ResolvePackagePath(string sourceFile, PackageInfo packageInfo)
        {
            if (packageInfo == null || string.IsNullOrEmpty(packageInfo.resolvedPath))
            {
                return null;
            }

            string normalizedSource = sourceFile.Replace('\\', '/');
            string relativePath = null;

            string assetPath = packageInfo.assetPath;
            if (!string.IsNullOrEmpty(assetPath))
            {
                string prefix = assetPath.Replace('\\', '/').TrimEnd('/') + "/";
                if (normalizedSource.StartsWith(prefix, StringComparison.OrdinalIgnoreCase))
                {
                    relativePath = normalizedSource.Substring(prefix.Length);
                }
            }

            if (string.IsNullOrEmpty(relativePath))
            {
                string root = packageInfo.resolvedPath.Replace('\\', '/').TrimEnd('/') + "/";
                if (normalizedSource.StartsWith(root, StringComparison.OrdinalIgnoreCase))
                {
                    relativePath = normalizedSource.Substring(root.Length);
                }
            }

            if (string.IsNullOrEmpty(relativePath))
            {
                return null;
            }

            try
            {
                return Path.GetFullPath(Path.Combine(
                    packageInfo.resolvedPath,
                    relativePath.Replace('/', Path.DirectorySeparatorChar)));
            }
            catch (ArgumentException)
            {
                return null;
            }
            catch (NotSupportedException)
            {
                return null;
            }
            catch (PathTooLongException)
            {
                return null;
            }
        }

        private static PackageInfo FindPackageInfo(string assetPath)
        {
            if (string.IsNullOrEmpty(assetPath))
            {
                return null;
            }

            try
            {
                return PackageInfo.FindForAssetPath(assetPath);
            }
            catch (Exception)
            {
                return null;
            }
        }

        private static string FindCommonDirectory(IReadOnlyList<string> files)
        {
            if (files == null || files.Count == 0)
            {
                return null;
            }

            string common = Path.GetDirectoryName(files[0]);
            if (string.IsNullOrEmpty(common))
            {
                return null;
            }

            for (int i = 1; i < files.Count; i++)
            {
                string directory = Path.GetDirectoryName(files[i]);
                while (!string.IsNullOrEmpty(common) && !IsSameOrAncestor(common, directory))
                {
                    common = Path.GetDirectoryName(common);
                }

                if (string.IsNullOrEmpty(common))
                {
                    return null;
                }
            }

            return common;
        }

        private static string FindAssemblyDefinitionDirectory(string startDirectory, string boundary)
        {
            string directory = startDirectory;
            while (!string.IsNullOrEmpty(directory))
            {
                if (ContainsAssemblyDefinition(directory))
                {
                    return directory;
                }

                if (PathsEqual(directory, boundary) || !IsSameOrAncestor(boundary, directory))
                {
                    break;
                }

                directory = Path.GetDirectoryName(directory);
            }

            return startDirectory;
        }

        private static bool ContainsAssemblyDefinition(string directory)
        {
            try
            {
                foreach (string file in Directory.GetFiles(directory, "*.asmdef"))
                {
                    if (IsAssemblyDefinitionFile(file))
                    {
                        return true;
                    }
                }

                foreach (string file in Directory.GetFiles(directory, "*.asmref"))
                {
                    if (IsAssemblyDefinitionFile(file))
                    {
                        return true;
                    }
                }
            }
            catch (IOException)
            {
            }
            catch (UnauthorizedAccessException)
            {
            }

            return false;
        }

        private static bool IsAssemblyDefinitionFile(string path)
        {
            string extension = Path.GetExtension(path);
            return string.Equals(extension, ".asmdef", StringComparison.OrdinalIgnoreCase) ||
                   string.Equals(extension, ".asmref", StringComparison.OrdinalIgnoreCase);
        }

        private static bool HasReparsePoint(string directory)
        {
            try
            {
                return (File.GetAttributes(directory) & FileAttributes.ReparsePoint) != 0;
            }
            catch (IOException)
            {
                return true;
            }
            catch (UnauthorizedAccessException)
            {
                return true;
            }
        }

        private static bool ContainsRelevantChange(string[] files)
        {
            if (files == null)
            {
                return false;
            }

            foreach (string file in files)
            {
                if (string.IsNullOrEmpty(file))
                {
                    continue;
                }

                if (_relevantExtensions.Contains(Path.GetExtension(file)))
                {
                    return true;
                }
            }

            return false;
        }

        private static string MakeUniqueProjectName(string baseName, HashSet<string> usedNames)
        {
            if (string.IsNullOrEmpty(baseName))
            {
                baseName = "Assembly";
            }

            string candidate = baseName;
            int suffix = 2;
            while (!usedNames.Add(candidate))
            {
                candidate = baseName + "_" + suffix;
                suffix++;
            }

            return candidate;
        }

        private static string NormalizeDirectory(string directory)
        {
            if (string.IsNullOrEmpty(directory))
            {
                return string.Empty;
            }

            try
            {
                string fullPath = Path.GetFullPath(directory);
                if (fullPath.Length <= 3)
                {
                    return fullPath;
                }

                string trimmed = fullPath.TrimEnd(
                    Path.DirectorySeparatorChar,
                    Path.AltDirectorySeparatorChar);
                return string.IsNullOrEmpty(trimmed) ? fullPath : trimmed;
            }
            catch (ArgumentException)
            {
                return directory;
            }
            catch (NotSupportedException)
            {
                return directory;
            }
            catch (PathTooLongException)
            {
                return directory;
            }
        }

        private static bool PathsEqual(string left, string right)
        {
            return string.Equals(left, right, StringComparison.OrdinalIgnoreCase);
        }

        private static bool IsSameOrAncestor(string ancestor, string path)
        {
            if (string.IsNullOrEmpty(ancestor) || string.IsNullOrEmpty(path))
            {
                return false;
            }

            if (PathsEqual(ancestor, path))
            {
                return true;
            }

            char lastCharacter = ancestor[ancestor.Length - 1];
            string prefix = lastCharacter == Path.DirectorySeparatorChar || lastCharacter == Path.AltDirectorySeparatorChar
                ? ancestor
                : ancestor + Path.DirectorySeparatorChar;

            return path.StartsWith(prefix, StringComparison.OrdinalIgnoreCase);
        }

